import sys
import os

# Ensure backend and packages are on path
sys.path.insert(0, os.path.abspath(os.path.dirname(__file__)))

from fastapi.testclient import TestClient
from app.main import app
from app.database.connection import SessionLocal
from app.models.research_knowledge import PreviousProject, SharedPaperKnowledge
from app.models.student import Student

client = TestClient(app)

def test_module2_full_suite():
    print("======================================================================")
    print("  ROSS-SEARCH MODULE 2 COMPREHENSIVE VERIFICATION SUITE")
    print("  End-to-End Automation, AI Engine & Automated PDF Downloads")
    print("======================================================================")

    # 1. [Riya Saha - ID: 715] Published Papers & Automated PDF Downloader
    print("\n▶ 1. Testing Academic Papers Catalog & Automated PDF Download [Riya Saha - ID: 715]")
    res_papers = client.get("/api/research/academic-papers")
    assert res_papers.status_code == 200
    papers = res_papers.json()
    assert len(papers) >= 6, f"Expected at least 6 papers, got {len(papers)}"
    print(f"  ✔ Retrieved {len(papers)} published academic research papers")

    # Test Cyber Security domain filter
    res_cyber = client.get("/api/research/academic-papers?domain=Cyber Security")
    assert res_cyber.status_code == 200
    cyber_papers = res_cyber.json()
    assert len(cyber_papers) >= 2
    print(f"  ✔ Cyber Security domain filter returned {len(cyber_papers)} papers")

    # Test Automated PDF Downloader Endpoint
    res_pdf_dl = client.get(f"/api/research/download-paper/{papers[0]['id']}")
    assert res_pdf_dl.status_code == 200
    assert res_pdf_dl.headers["content-type"] == "application/pdf"
    assert len(res_pdf_dl.content) > 1000
    print(f"  ✔ Automated PDF generation & download verified: {len(res_pdf_dl.content)} bytes generated")

    # Test Previous Projects Retrieval
    res_prev = client.get("/api/research/previous-projects")
    assert res_prev.status_code == 200
    projects = res_prev.json()
    assert len(projects) >= 8
    print(f"  ✔ Retrieved {len(projects)} previous departmental FYP projects from DB")

    # 2. [Robayet Islam - ID: 809] AI 9-Point Structured Paper Summarizer
    print("\n▶ 2. Testing AI 9-Point Structured Paper Summarizer [Robayet Islam - ID: 809]")
    sample_text = """
    Deep Learning for SCADA Cyber Security in Industrial Smart Grids
    Problem Statement:
    Cyber-physical attacks on critical SCADA infrastructure cause power grid disruption and cannot be detected by threshold rules.
    Objectives:
    1. Develop autoencoder anomaly detection.
    2. Mitigate false alarms in industrial telemetry.
    Methodology:
    Ensemble deep autoencoders coupled with Random Forest classifiers on network packets.
    Dataset:
    Evaluated on Tennessee Eastman SCADA process dataset with 50,000 telemetry records.
    Model and Technology:
    PyTorch autoencoder, Scikit-learn Random Forest, Python 3.12.
    Findings:
    Achieved 97.4% detection accuracy with 0.8% false positive rate.
    Limitations:
    High memory footprint during real-time packet inspection.
    Research Gap:
    Absence of zero-day attack identification without labeled signatures.
    Future Work:
    Deployment on edge micro-controllers and FPGA accelerators.
    """
    res_sum = client.post("/api/research/summarize-pdf", data={"raw_text": sample_text})
    assert res_sum.status_code == 200
    summary = res_sum.json()
    assert "ai_engine" in summary
    print(f"  ✔ Summary successfully generated by engine: '{summary['ai_engine']}'")

    required_sections = [
        "problem_statement", "objectives", "methodology", "dataset",
        "model_technology", "findings", "limitations", "research_gap", "future_work"
    ]
    for sec in required_sections:
        assert sec in summary and len(summary[sec]) > 8, f"Section {sec} missing"
    print(f"  ✔ Verified all 9 distinct academic sections")

    # 3. [Tamim Hasan Sami - ID: 313] Topic Similarity & Duplicate Rejection
    print("\n▶ 3. Testing Topic Similarity & Duplicate Rejection [Tamim Hasan Sami - ID: 313]")
    # High overlap test -> Must REJECT registration
    dup_req = {
        "title": "Cyber-Physical SCADA Network Threat Detection Using Deep Autoencoders and Random Forest",
        "domain": "Cyber Security",
        "abstract": "Deep autoencoders and random forest on SCADA network packets."
    }
    res_dup = client.post("/api/research/check-similarity", json=dup_req)
    assert res_dup.status_code == 200
    dup_data = res_dup.json()
    assert dup_data["can_register"] is False, "Duplicate topic should be rejected!"
    assert dup_data["highest_similarity"] >= 70.0
    print(f"  ✔ Duplicate topic successfully rejected (Similarity: {dup_data['highest_similarity']}%, can_register=False)")

    # Novel topic test -> Must APPROVE registration
    novel_req = {
        "title": "Quantum Key Distribution Protocols for Deep Space Optical Laser Satellites",
        "domain": "Cyber Security",
        "abstract": "Entangled photon state routing through high atmospheric turbulence."
    }
    res_novel = client.post("/api/research/check-similarity", json=novel_req)
    assert res_novel.status_code == 200
    novel_data = res_novel.json()
    assert novel_data["can_register"] is True, "Novel topic should be approved!"
    assert novel_data["highest_similarity"] < 50.0
    print(f"  ✔ Novel topic successfully approved (Similarity: {novel_data['highest_similarity']}%, can_register=True)")

    # 4. [Tamim Hasan Sami - ID: 313] Shared Paper Knowledge Repository
    print("\n▶ 4. Testing Shared Paper Knowledge Repository [Tamim Hasan Sami - ID: 313]")
    res_shared = client.get("/api/research/shared-knowledge")
    assert res_shared.status_code == 200
    shared_list = res_shared.json()
    assert len(shared_list) >= 3
    print(f"  ✔ Retrieved {len(shared_list)} persistent shared papers from database")

    print("\n======================================================================")
    print("  🎉 ALL ENHANCED MODULE 2 TESTS COMPLETED WITH 100% SUCCESS!")
    print("======================================================================")

if __name__ == "__main__":
    test_module2_full_suite()
